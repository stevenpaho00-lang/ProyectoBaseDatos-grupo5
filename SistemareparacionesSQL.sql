-- Procedimiento para registrar una nueva reparacion
CREATE PROCEDURE sp_RegistrarReparacion
@EquipoID INT,
@FechaSolicitud DATETIME
AS
BEGIN
INSERT INTO REPARACIONES(EQUIPOID,FECHASOLICITUD,ESTADO)
VALUES(@EquipoID,@FechaSolicitud,'PENDIENTE')
END
GO
-- Procedimiento para asignar un tecnico a una reparacion
CREATE PROCEDURE sp_AsignarTecnico
@ReparacionID INT,
@TecnicoID INT
AS
BEGIN
INSERT INTO ASIGNACIONES(REPARACIONID,TECNICOID,FECHAASIGNACION)
VALUES(@ReparacionID,@TecnicoID,GETDATE())
END
GO
-- Trigger para cambiar el estado cuando una reparacion finaliza
CREATE TRIGGER tr_FinalizarReparacion
ON DETALLESREPARACION
AFTER UPDATE
AS
BEGIN
UPDATE REPARACIONES
SET ESTADO='COMPLETADO'
FROM REPARACIONES R
INNER JOIN inserted I
ON R.REPARACIONID=I.REPARACIONID
WHERE I.FECHAFIN IS NOT NULL
END
GO
-- Prueba del procedimiento registrar reparacion
EXEC sp_RegistrarReparacion 1,GETDATE()
GO
-- Prueba del procedimiento asignar tecnico
EXEC sp_AsignarTecnico 1,4
GO
-- Informe de asignaciones
SELECT U.NOMBRE AS USUARIO,E.MODELO,T.NOMBRE AS TECNICO
FROM USUARIOS U
INNER JOIN EQUIPOS E ON U.USUARIOID=E.USUARIOID
INNER JOIN REPARACIONES R ON E.EQUIPOID=R.EQUIPOID
INNER JOIN ASIGNACIONES A ON R.REPARACIONID=A.REPARACIONID
INNER JOIN TECNICOS T ON A.TECNICOID=T.TECNICOID
GO
-- Cantidad de reparaciones por tecnico
SELECT T.NOMBRE,COUNT(A.REPARACIONID) AS TOTALREPARACIONES
FROM TECNICOS T
INNER JOIN ASIGNACIONES A ON T.TECNICOID=A.TECNICOID
GROUP BY T.NOMBRE
GO
-- Equipos de un modelo especifico ingresados en el ultimo mes
SELECT E.MODELO,R.FECHASOLICITUD
FROM EQUIPOS E
INNER JOIN REPARACIONES R ON E.EQUIPOID=R.EQUIPOID
WHERE E.MODELO='PLAYSTATION 5'
AND R.FECHASOLICITUD>=DATEADD(MONTH,-1,GETDATE())
GO
